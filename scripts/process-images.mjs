// Resizes raw product photos from assets/<slug>/*.{jpg,jpeg,png} (gitignored,
// not part of the build) into the thumb/full webp pairs that ship from
// public/products/<slug>/, and regenerates the manifest the site reads to
// know how many photos each product has. Re-run anytime; files whose output
// is newer than the source are skipped, but the manifest is always rewritten
// from what's currently on disk.
import { mkdir, readdir, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { resizeProductImage, SIZES } from './lib/resizeProductImage.mjs'
import { SOURCE_EXTENSIONS } from './lib/sourceExtensions.mjs'

const rawDir = path.resolve(import.meta.dirname, '..', 'assets')
const outDir = path.resolve(import.meta.dirname, '..', 'public', 'products')
const manifestPath = path.resolve(import.meta.dirname, '..', 'src', 'data', 'productImageCounts.generated.ts')

async function findRawPhotosBySlug() {
  const slugDirs = await readdir(rawDir, { withFileTypes: true }).catch(() => [])
  const bySlug = new Map()

  for (const slugDir of slugDirs) {
    if (!slugDir.isDirectory()) continue
    const dirPath = path.join(rawDir, slugDir.name)
    const files = (await readdir(dirPath))
      .filter((file) => SOURCE_EXTENSIONS.has(path.extname(file).toLowerCase()))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
      .map((file) => path.join(dirPath, file))

    if (files.length > 0) bySlug.set(slugDir.name, files)
  }

  return bySlug
}

async function isUpToDate(sourcePath, outPath) {
  const [sourceStat, outStat] = await Promise.all([stat(sourcePath), stat(outPath).catch(() => null)])
  return outStat !== null && outStat.mtimeMs >= sourceStat.mtimeMs
}

async function processSlug(slug, sourcePaths) {
  const targetDir = path.join(outDir, slug)
  await mkdir(targetDir, { recursive: true })

  for (const [index, sourcePath] of sourcePaths.entries()) {
    const n = index + 1
    for (const [variant, width] of Object.entries(SIZES)) {
      const outPath = path.join(targetDir, `${n}-${variant}.webp`)
      if (await isUpToDate(sourcePath, outPath)) continue

      await resizeProductImage(sourcePath, outPath, width)
      console.log(`wrote ${path.relative(outDir, outPath)}`)
    }
  }
}

async function writeManifest(bySlug) {
  const counts = Object.fromEntries(
    [...bySlug.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([slug, files]) => [slug, files.length]),
  )
  const body = JSON.stringify(counts, null, 2).replace(/"([A-Za-z_$][\w$]*)":/g, '$1:')
  const contents = `// Generated by \`npm run process-images\` — do not edit by hand.
// Maps product slug to how many photos exist for it under public/products/<slug>/.
export const productImageCounts: Record<string, number> = ${body}
`
  await writeFile(manifestPath, contents)
  console.log(`wrote ${path.relative(path.resolve(import.meta.dirname, '..'), manifestPath)}`)
}

async function main() {
  const bySlug = await findRawPhotosBySlug()
  if (bySlug.size === 0) {
    console.log(`No raw photos found under ${rawDir}. Expected assets/<slug>/1.jpg, 2.jpg, ...`)
    return
  }
  for (const [slug, sourcePaths] of bySlug) {
    await processSlug(slug, sourcePaths)
  }
  await writeManifest(bySlug)
}

main()
